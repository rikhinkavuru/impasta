function dedupeByWord(list) {
  const seen = new Set();
  const out = [];
  for (const row of list) {
    const w = row[0].toLowerCase();
    if (seen.has(w)) continue;
    seen.add(w);
    out.push(row);
  }
  return out;
}

const unique = dedupeByWord(rows);

const header = `import type { WordPair } from "./wordBank.types";

function p(word: string, easy: string, medium: string, hard: string, category: string): WordPair {
  return { word, clues: { easy, medium, hard }, category };
}

`;

const body = unique
  .map(
    ([word, easy, medium, hard, cat]) =>
      `  p(${JSON.stringify(word)}, ${JSON.stringify(easy)}, ${JSON.stringify(medium)}, ${JSON.stringify(hard)}, ${JSON.stringify(cat)})`,
  )
  .join(",\n");

const file = `${header}
export const wordBank: WordPair[] = [
${body},
];
`;

